# Kayak's splash (0.6: draft A, smooth, a close drop shadow) drawn with GDI+ and written as firmware/gen/kayak_splash.h:
# the picture's top SPLASH_H rows in RGB565, run-length coded (count, colour pairs); the version line under it is
# the firmware's (dinghy.c splash). Also docs/card.png, the Firmware Hub's card (240 x 240).
#   powershell -File tools/make_splash.ps1          (Windows: System.Drawing; the header is committed)
param([string]$Root = (Split-Path -Parent $PSScriptRoot))
Add-Type -AssemblyName System.Drawing
$H = 206                                         # the rows the picture keeps (the version line goes under it)

function C([int]$r, [int]$g, [int]$b, [int]$a = 255) { [System.Drawing.Color]::FromArgb($a, $r, $g, $b) }
$ORANGE = C 255 140 26; $MID = C 190 95 15; $DARK = C 70 36 6; $BLACK = C 0 0 0

# the kayaker, in the 48 x 28 design's units (x 4 + 24 pixels)
function P([double]$x, [double]$y, [double]$ox, [double]$oy) { New-Object System.Drawing.PointF ([float]($ox + $x * 4)), ([float]($oy + $y * 4)) }
$HULL = @(@(0.6,21.6),@(9,20.2),@(18,18.9),@(32,16.6),@(47.6,14.2),@(44,17.6),@(38,20.4),@(26,22.4),@(14,23.8),@(6,23.4))
function RoundPen($color, [float]$w) { $p = New-Object System.Drawing.Pen $color, $w; $p.StartCap = 'Round'; $p.EndCap = 'Round'; $p }
function Figure($g, $color, [double]$dx, [double]$dy, $gap) {
    $ox = 24 + $dx; $oy = 24 + $dy
    $b = New-Object System.Drawing.SolidBrush $color
    $g.FillClosedCurve($b, [System.Drawing.PointF[]]($HULL | ForEach-Object { P $_[0] $_[1] $ox $oy }), 'Winding', 0.35)
    if ($gap) { $g.DrawLine((RoundPen $gap 10), (P 43.5 1.5 $ox $oy), (P 11 25.5 $ox $oy)) }   # (the paddle in front of the hull)
    $g.DrawLine((RoundPen $color 5), (P 43.5 1.5 $ox $oy), (P 11 25.5 $ox $oy))
    $pb = RoundPen $color 13
    $g.DrawLine($pb, (P 44.6 0.4 $ox $oy), (P 41 4 $ox $oy))
    $g.DrawLine($pb, (P 9.8 27.4 $ox $oy), (P 12.6 24.2 $ox $oy))
    $g.DrawLine((RoundPen $color 18), (P 27 10.4 $ox $oy), (P 25 18.2 $ox $oy))
    $g.DrawLine((RoundPen $color 8), (P 27.4 11.6 $ox $oy), (P 33.6 8.8 $ox $oy))
    $hc = P 27.5 4.6 $ox $oy
    $g.FillEllipse($b, [float]($hc.X - 12), [float]($hc.Y - 12), [float]24, [float]24)
}

$bm = New-Object System.Drawing.Bitmap 240, 240
$g = [System.Drawing.Graphics]::FromImage($bm); $g.SmoothingMode = 'AntiAlias'; $g.TextRenderingHint = 'AntiAliasGridFit'; $g.Clear($BLACK)
for ($k = 3; $k -ge 1; $k--) { Figure $g (C 120 60 8 (60 + 40 * (3 - $k))) $k $k $null }   # the shadow, close: 3 .. 1 px
Figure $g $ORANGE 0 0 $BLACK
foreach ($row in @(@(148, $ORANGE, 2.5), @(158, $MID, 2))) {   # the water: two smooth waves
    $pts = [System.Drawing.PointF[]](0..48 | ForEach-Object { New-Object System.Drawing.PointF ([float]($_ * 5)), ([float]($row[0] + 3 * [Math]::Sin($_ * 0.9 + $row[0]))) })
    $g.DrawCurve((New-Object System.Drawing.Pen $row[1], $row[2]), $pts)
}
$f = New-Object System.Drawing.Font 'Segoe UI Black', 38, ([System.Drawing.FontStyle]::Regular), ([System.Drawing.GraphicsUnit]::Pixel)
$sf = New-Object System.Drawing.StringFormat; $sf.Alignment = 'Center'
$g.DrawString('KAYAK', $f, (New-Object System.Drawing.SolidBrush $DARK), (New-Object System.Drawing.RectangleF 2, 168, 240, 60), $sf)
$g.DrawString('KAYAK', $f, (New-Object System.Drawing.SolidBrush $ORANGE), (New-Object System.Drawing.RectangleF 0, 166, 240, 60), $sf)
$g.FillRectangle((New-Object System.Drawing.SolidBrush $BLACK), 0, $H, 240, 240 - $H)

# RGB565, run-length coded
$runs = New-Object System.Collections.Generic.List[int]
$last = -1; $n = 0
for ($y = 0; $y -lt $H; $y++) {
    for ($x = 0; $x -lt 240; $x++) {
        $c = $bm.GetPixel($x, $y)
        $v = (([int]$c.R -shr 3) -shl 11) -bor (([int]$c.G -shr 2) -shl 5) -bor ([int]$c.B -shr 3)   # ([int]: a byte shifted stays a byte)
        if ($v -eq $last -and $n -lt 65535) { $n++ } else { if ($n) { $runs.Add($n); $runs.Add($last) }; $last = $v; $n = 1 }
    }
}
$runs.Add($n); $runs.Add($last)
$L = New-Object System.Collections.Generic.List[string]
$L.Add('/* generated by tools/make_splash.ps1: the splash (draft A), RGB565 run-length coded: count, colour */')
$L.Add('#pragma once')
$L.Add("#define SPLASH_H $H")
$L.Add("static const uint16_t SPLASH_RLE[$($runs.Count)] = {")
for ($i = 0; $i -lt $runs.Count; $i += 12) { $L.Add('    ' + (($runs[$i..([Math]::Min($i + 12, $runs.Count) - 1)] | ForEach-Object { '0x{0:x4}' -f $_ }) -join ', ') + ',') }
$L.Add('};')
[IO.File]::WriteAllText((Join-Path $Root 'firmware\gen\kayak_splash.h'), ($L -join "`n") + "`n", (New-Object Text.UTF8Encoding $false))
$bm.Save((Join-Path $Root 'docs\card.png'), [System.Drawing.Imaging.ImageFormat]::Png)
"splash: $($runs.Count / 2) runs, $($runs.Count * 2) B"
