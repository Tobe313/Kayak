"""The UI fonts (firmware/gen/felucca_font.h) from a Terminus BDF: FONT_S the BDF's glyphs (ASCII 32..126), FONT_L the
same doubled (ASCII 32..95: capitals, digits, signs). 4 bits a pixel (Terminus is 1 bit: 0 or 15), the bitmap
FONT_PAD (x the scale) pixels left of the pen, as gfx.c's felucca_font_t reads them.

  tools/gen_font.py ter-u18n.bdf firmware/gen/felucca_font.h     (Kayak since 0.6: Terminus 18, 10 x 18 and 20 x 36)

Terminus (SIL OFL 1.1, assets/fonts/Terminus-LICENSE.txt): https://terminus-font.sourceforge.net/"""
import sys
from pathlib import Path

PAD = 2


def read_bdf(path):
    asc = 0
    glyphs = {}
    cur = None
    rows = None
    for line in Path(path).read_text(encoding="latin-1").splitlines():
        w = line.split()
        if not w:
            continue
        if w[0] == "FONT_ASCENT":
            asc = int(w[1])
        elif w[0] == "STARTCHAR":
            cur = {}
        elif w[0] == "ENCODING":
            cur["enc"] = int(w[1])
        elif w[0] == "DWIDTH":
            cur["adv"] = int(w[1])
        elif w[0] == "BBX":
            cur["bbx"] = tuple(int(v) for v in w[1:5])
        elif w[0] == "BITMAP":
            rows = []
        elif w[0] == "ENDCHAR":
            cur["rows"] = rows
            glyphs[cur["enc"]] = cur
            rows = None
        elif rows is not None:
            rows.append(int(w[0], 16) << (8 - 4 * len(w[0]) % 8 if len(w[0]) % 2 else 0))
            cur.setdefault("hexlen", len(w[0]))
    return asc, glyphs


def cell(asc, height, g):
    """the glyph as rows of 0/1, in a cell of `height` rows and adv + 2 PAD columns"""
    bw, bh, xo, yo = g["bbx"]
    width = g["adv"] + 2 * PAD
    grid = [[0] * width for _ in range(height)]
    top = asc - (yo + bh)
    nbits = g["hexlen"] * 4
    for r, bits in enumerate(g["rows"]):
        for c in range(bw):
            if bits >> (nbits - 1 - c) & 1:
                y, x = top + r, PAD + xo + c
                if 0 <= y < height and 0 <= x < width:
                    grid[y][x] = 1
    return grid


def pack(grid):
    out = []
    w = len(grid[0])
    for row in grid:
        for x in range(0, w, 2):
            a = 15 if row[x] else 0
            b = 15 if x + 1 < w and row[x + 1] else 0
            out.append(a << 4 | b)
    return out


def font(name, glyphs, first, last, height, asc, scale):
    data, off, adv, bw = [], [], [], []
    for ch in range(first, last + 1):
        g = glyphs.get(ch) or glyphs[ord("?")]
        grid = cell(asc, height, g)
        if scale > 1:                               # doubled: each pixel 2 x 2, the pad doubled with it
            grid = [[v for v in row for _ in range(scale)] for row in grid for _ in range(scale)]
        off.append(len(data))
        adv.append(g["adv"] * scale)
        bw.append(len(grid[0]))
        data += pack(grid)
    L = [f"static const uint8_t {name}_DATA[{len(data)}] = {{"]
    for i in range(0, len(data), 24):
        L.append("    " + ", ".join(f"0x{v:02x}" for v in data[i:i + 24]) + ",")
    L.append("};")
    L.append(f"static const uint16_t {name}_OFF[{len(off)}] = {{{', '.join(map(str, off))}}};")
    L.append(f"static const uint8_t {name}_ADV[{len(adv)}] = {{{', '.join(map(str, adv))}}};")
    L.append(f"static const uint8_t {name}_BW[{len(bw)}] = {{{', '.join(map(str, bw))}}};")
    L.append(f"static const felucca_font_t {name} = {{ {height * scale}, {PAD * scale}, {first}, {last}, "
             f"{name}_ADV, {name}_BW, {name}_OFF, {name}_DATA }};")
    return L


def main(src, dst):
    asc, glyphs = read_bdf(src)
    height = max(g["bbx"][1] for g in glyphs.values() if 32 <= g["enc"] < 127)
    L = [f"/* generated by tools/gen_font.py from {Path(src).name} (FONT_S cut to ASCII 32..126, the rest shows as ?) */",
         "#pragma once", "#include <stdint.h>", f"#define FONT_PAD {PAD}  /* x scale for L, see below */", ""]
    L += font("FONT_S", glyphs, 32, 126, height, asc, 1)
    L += [""]
    L += font("FONT_L", glyphs, 32, 95, height, asc, 2)
    Path(dst).write_text("\n".join(L) + "\n")
    print(f"fonts: {dst} (S {height} px, L {2 * height} px)")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
